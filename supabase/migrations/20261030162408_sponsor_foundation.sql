-- Fundação do novo domínio de patrocinadores.
--
-- Esta migração é intencionalmente aditiva: o modelo legado de expositores
-- permanece disponível até a conclusão da migração das telas e dos fluxos.

create table if not exists public.sponsors (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  username text not null,
  username_normalized text generated always as (lower(btrim(username))) stored,
  password_hash text not null,
  encrypted_password jsonb not null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_by uuid null references auth.users (id) on delete set null,
  updated_by uuid null references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sponsors_name_length check (char_length(btrim(name)) between 1 and 160),
  constraint sponsors_username_length check (char_length(btrim(username)) between 3 and 80),
  constraint sponsors_username_trimmed check (username = btrim(username)),
  constraint sponsors_encrypted_password_object check (jsonb_typeof(encrypted_password) = 'object')
);

create unique index if not exists uq_sponsors_username_normalized
  on public.sponsors (username_normalized);

create index if not exists idx_sponsors_status_name
  on public.sponsors (status, name);

create table if not exists public.sponsor_sessions (
  id uuid primary key default gen_random_uuid(),
  sponsor_id uuid not null references public.sponsors (id) on delete cascade,
  token_hash text not null,
  expires_at timestamptz not null,
  last_seen_at timestamptz null,
  revoked_at timestamptz null,
  created_at timestamptz not null default now(),
  constraint sponsor_sessions_token_hash_length check (char_length(token_hash) >= 32),
  constraint sponsor_sessions_expiry_after_creation check (expires_at > created_at)
);

create unique index if not exists uq_sponsor_sessions_token_hash
  on public.sponsor_sessions (token_hash);

create index if not exists idx_sponsor_sessions_active
  on public.sponsor_sessions (sponsor_id, expires_at)
  where revoked_at is null;

create table if not exists public.sponsor_auth_attempts (
  id uuid primary key default gen_random_uuid(),
  username_normalized text not null,
  fingerprint_hash text not null,
  succeeded boolean not null default false,
  attempted_at timestamptz not null default now(),
  constraint sponsor_auth_attempts_fingerprint_length check (char_length(fingerprint_hash) = 64)
);

create index if not exists idx_sponsor_auth_attempts_rate_limit
  on public.sponsor_auth_attempts (username_normalized, fingerprint_hash, attempted_at desc);

create table if not exists public.sponsor_team_members (
  id uuid primary key default gen_random_uuid(),
  member_number bigint generated by default as identity unique,
  sponsor_id uuid not null references public.sponsors (id) on delete cascade,
  full_name text not null,
  job_title text null,
  status text not null default 'active' check (status in ('active', 'inactive')),
  created_by_user_id uuid null references auth.users (id) on delete set null,
  created_by_sponsor boolean not null default false,
  updated_by_user_id uuid null references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint sponsor_team_members_name_length check (char_length(btrim(full_name)) between 1 and 160),
  constraint sponsor_team_members_job_title_length check (job_title is null or char_length(btrim(job_title)) between 1 and 120)
);

create index if not exists idx_sponsor_team_members_sponsor_status
  on public.sponsor_team_members (sponsor_id, status, full_name);

create table if not exists public.sponsor_participant_records (
  id uuid primary key default gen_random_uuid(),
  sponsor_id uuid not null references public.sponsors (id) on delete cascade,
  event_id uuid not null references public.events (id) on delete cascade,
  participant_id uuid not null references public.participants (id) on delete cascade,
  captured_at timestamptz not null,
  received_at timestamptz not null default now(),
  source text not null default 'badge_qr' check (source in ('badge_qr', 'offline_badge_qr')),
  client_capture_id uuid null,
  invalidated_at timestamptz null,
  invalidated_by uuid null references auth.users (id) on delete set null,
  invalidation_reason text null,
  constraint sponsor_participant_records_invalidation_pair check (
    (invalidated_at is null and invalidated_by is null)
    or (invalidated_at is not null and invalidated_by is not null)
  )
);

create unique index if not exists uq_sponsor_participant_records_active
  on public.sponsor_participant_records (sponsor_id, event_id, participant_id)
  where invalidated_at is null;

create unique index if not exists uq_sponsor_participant_records_client_capture
  on public.sponsor_participant_records (sponsor_id, client_capture_id)
  where client_capture_id is not null;

create index if not exists idx_sponsor_participant_records_event
  on public.sponsor_participant_records (sponsor_id, event_id, captured_at desc)
  where invalidated_at is null;

create table if not exists public.event_sponsor_data_settings (
  event_id uuid primary key references public.events (id) on delete cascade,
  share_email boolean not null default false,
  share_phone boolean not null default false,
  share_company boolean not null default false,
  share_profession boolean not null default false,
  share_job_title boolean not null default false,
  share_city boolean not null default false,
  share_state boolean not null default false,
  updated_by uuid null references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.participants
  add column if not exists company text null,
  add column if not exists job_title text null;

-- Cofre reversível exigido pelo negócio. O conteúdo é cifrado pela aplicação;
-- a chave nunca é persistida no banco e somente o servidor usa esta tabela.
create table if not exists public.user_password_vault (
  user_id uuid primary key references auth.users (id) on delete cascade,
  encrypted_password jsonb not null,
  updated_by uuid null references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_password_vault_encrypted_password_object check (jsonb_typeof(encrypted_password) = 'object')
);

-- Origem e ciência ficam registradas, mas não bloqueiam inscrições feitas pela recepção.
alter table public.event_registrations
  add column if not exists registration_source text not null default 'legacy',
  add column if not exists data_sharing_notice_version text null,
  add column if not exists data_sharing_notice_acknowledged_at timestamptz null;

alter table public.event_registrations
  drop constraint if exists event_registrations_registration_source_check;

alter table public.event_registrations
  add constraint event_registrations_registration_source_check
  check (registration_source in ('legacy', 'public_registration', 'reception', 'admin', 'import'));

drop trigger if exists trg_sponsors_updated_at on public.sponsors;
create trigger trg_sponsors_updated_at
before update on public.sponsors
for each row execute function public.set_updated_at();

drop trigger if exists trg_sponsor_team_members_updated_at on public.sponsor_team_members;
create trigger trg_sponsor_team_members_updated_at
before update on public.sponsor_team_members
for each row execute function public.set_updated_at();

drop trigger if exists trg_event_sponsor_data_settings_updated_at on public.event_sponsor_data_settings;
create trigger trg_event_sponsor_data_settings_updated_at
before update on public.event_sponsor_data_settings
for each row execute function public.set_updated_at();

drop trigger if exists trg_user_password_vault_updated_at on public.user_password_vault;
create trigger trg_user_password_vault_updated_at
before update on public.user_password_vault
for each row execute function public.set_updated_at();

-- Sem políticas para authenticated/anon: toda operação passa por rotas de servidor
-- que validam o papel administrativo ou a sessão própria do patrocinador.
alter table public.sponsors enable row level security;
alter table public.sponsor_sessions enable row level security;
alter table public.sponsor_auth_attempts enable row level security;
alter table public.sponsor_team_members enable row level security;
alter table public.sponsor_participant_records enable row level security;
alter table public.event_sponsor_data_settings enable row level security;
alter table public.user_password_vault enable row level security;

