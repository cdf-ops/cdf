alter table public.event_badge_settings
  add column if not exists background_path text null,
  add column if not exists layout jsonb not null default '{"elements":[]}'::jsonb,
  add column if not exists participant_label text not null default 'PARTICIPANTE',
  add column if not exists sponsor_label text not null default 'PATROCINADOR';

alter table public.event_badge_settings
  add constraint event_badge_settings_participant_label_length
    check (char_length(trim(participant_label)) between 1 and 40),
  add constraint event_badge_settings_sponsor_label_length
    check (char_length(trim(sponsor_label)) between 1 and 40);

alter table public.exhibitor_credentials
  add column if not exists qr_slug text null,
  add column if not exists credential_number bigint generated by default as identity;

create unique index if not exists uq_exhibitor_credentials_qr_slug
  on public.exhibitor_credentials (qr_slug)
  where qr_slug is not null;

create table if not exists public.sponsor_entry_checkins (
  id uuid primary key default gen_random_uuid(),
  sponsor_credential_id uuid not null references public.exhibitor_credentials (id) on delete cascade,
  event_day_id uuid not null references public.event_days (id) on delete cascade,
  operator_user_id uuid not null references auth.users (id),
  origin text not null default 'badge_qr',
  checked_in_at timestamptz not null default now(),
  deleted_at timestamptz null,
  deleted_by uuid null references auth.users (id)
);

create unique index if not exists uq_sponsor_entry_checkins_active
  on public.sponsor_entry_checkins (sponsor_credential_id, event_day_id)
  where deleted_at is null;

alter table public.sponsor_entry_checkins enable row level security;

create policy p_sponsor_entry_checkins_ops
on public.sponsor_entry_checkins
for all to authenticated
using (public.current_app_role() in ('super_adm', 'organizador', 'recepcao'))
with check (public.current_app_role() in ('super_adm', 'organizador', 'recepcao'));
