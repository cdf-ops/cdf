-- Embaixadores pertencem diretamente a um evento. Eles não são participantes
-- nem patrocinadores, mas recebem uma credencial própria para uso na recepção.

create table public.event_ambassadors (
  id uuid primary key default gen_random_uuid(),
  ambassador_number bigint generated by default as identity,
  event_id uuid not null references public.events (id) on delete restrict,
  full_name text not null,
  qr_slug text not null,
  status text not null default 'active',
  created_by uuid null references auth.users (id) on delete set null,
  updated_by uuid null references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint event_ambassadors_full_name_length check (char_length(trim(full_name)) between 2 and 160),
  constraint event_ambassadors_qr_slug_length check (char_length(qr_slug) between 16 and 128),
  constraint event_ambassadors_qr_slug_unique unique (qr_slug),
  constraint event_ambassadors_status_check check (status in ('active', 'inactive'))
);

create index idx_event_ambassadors_event_status_name
  on public.event_ambassadors (event_id, status, full_name);

create trigger trg_event_ambassadors_updated_at
before update on public.event_ambassadors
for each row execute function public.set_updated_at();

create table public.ambassador_entry_checkins (
  id uuid primary key default gen_random_uuid(),
  ambassador_id uuid not null references public.event_ambassadors (id) on delete restrict,
  event_day_id uuid not null references public.event_days (id) on delete restrict,
  operator_user_id uuid not null references auth.users (id) on delete restrict,
  origin text not null default 'badge_qr',
  checked_in_at timestamptz not null default now(),
  deleted_at timestamptz null,
  deleted_by uuid null references auth.users (id) on delete set null,
  constraint ambassador_entry_checkins_origin_check check (origin in ('badge_qr', 'manual'))
);

create unique index uq_ambassador_entry_checkins_active
  on public.ambassador_entry_checkins (ambassador_id, event_day_id)
  where deleted_at is null;

create index idx_ambassador_entry_checkins_day
  on public.ambassador_entry_checkins (event_day_id, checked_in_at desc)
  where deleted_at is null;

alter table public.event_ambassadors enable row level security;
alter table public.ambassador_entry_checkins enable row level security;

-- O aplicativo acessa essas tabelas apenas no servidor, depois de validar a
-- sessão. Nenhum acesso direto é concedido a anon/authenticated.
revoke all on table public.event_ambassadors from anon, authenticated;
revoke all on table public.ambassador_entry_checkins from anon, authenticated;
grant select, insert, update, delete on table public.event_ambassadors to service_role;
grant select, insert, update, delete on table public.ambassador_entry_checkins to service_role;
grant usage, select on sequence public.event_ambassadors_ambassador_number_seq to service_role;
